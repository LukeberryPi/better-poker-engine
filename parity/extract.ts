import { readdir, readFile } from "node:fs/promises";
import path from "node:path";

export type DoctestEntry = {
  readonly id: string;
  readonly file: string;
  readonly examples: number;
};
export type UnitTestEntry = { readonly id: string; readonly file: string };

type Scope = {
  readonly name: string;
  readonly indent: number;
  readonly kind: "class" | "def";
};

const pinnedCommit = "abf7952";
const scopeHeader = /^(\s*)(?:async\s+)?(class|def)\s+([A-Za-z_]\w*)/;
const testCaseClass = /^class\s+([A-Za-z_]\w*)\s*\(/;
const testMethod = /^\s+def\s+(test_\w+)\s*\(/;
const topLevelFunction = /^(?:async\s+)?def\s/;

function moduleName(file: string): string {
  return file.replace(/\.py$/, "").split("/").join(".");
}

function indentOf(line: string): number {
  return line.length - line.trimStart().length;
}

function tripleQuoteCount(line: string): number {
  return line.match(/"""|'''/g)?.length ?? 0;
}

/** Names follow `doctest.DocTestFinder`: module path, then the qualified name. */
export function doctestsIn(file: string, source: string): DoctestEntry[] {
  const module = moduleName(file);
  const counts = new Map<string, number>();
  let scopes: Scope[] = [];
  let insideString = false;
  for (const line of source.split("\n")) {
    const trimmed = line.trim();
    if (trimmed.startsWith(">>>")) {
      if (scopes.slice(0, -1).some((scope) => scope.kind === "def")) {
        throw new Error(`${file}: doctest finder skips nested functions`);
      }
      const id = [module, ...scopes.map((scope) => scope.name)].join(".");
      counts.set(id, (counts.get(id) ?? 0) + 1);
    }
    if (!insideString && trimmed !== "") {
      const indent = indentOf(line);
      scopes = scopes.filter((scope) => scope.indent < indent);
      const match = scopeHeader.exec(line);
      const name = match?.[3];
      if (name !== undefined) {
        const kind = match?.[2] === "class" ? "class" : "def";
        scopes.push({ name, indent, kind });
      }
    }
    if (tripleQuoteCount(line) % 2 === 1) insideString = !insideString;
  }
  return [...counts].map(([id, examples]) => ({ id, file, examples }));
}

/** Names follow `unittest`: module path, `TestCase` class, method. */
export function unitTestsIn(file: string, source: string): UnitTestEntry[] {
  const module = moduleName(file);
  const tests: UnitTestEntry[] = [];
  let testCase: string | undefined;
  for (const line of source.split("\n")) {
    const caseName = testCaseClass.exec(line)?.[1];
    if (caseName !== undefined) testCase = caseName;
    else if (topLevelFunction.test(line)) testCase = undefined;
    const method = testMethod.exec(line)?.[1];
    if (method === undefined) continue;
    if (testCase === undefined) {
      throw new Error(`${file}: ${method} is outside a TestCase`);
    }
    tests.push({ id: `${module}.${testCase}.${method}`, file });
  }
  return tests;
}

async function pythonFiles(root: string, directory: string): Promise<string[]> {
  const entries = await readdir(path.join(root, directory), {
    withFileTypes: true,
  });
  const files = await Promise.all(
    entries.map((entry) => {
      const relative = path.posix.join(directory, entry.name);
      if (entry.isDirectory()) return pythonFiles(root, relative);
      return entry.name.endsWith(".py") ? [relative] : [];
    })
  );
  return files.flat().sort();
}

function manifestSource(
  commit: string,
  unitTests: readonly UnitTestEntry[],
  doctests: readonly DoctestEntry[]
): string {
  const unitLines = unitTests.map(
    (entry) => `  ${JSON.stringify(entry.id)}: ${JSON.stringify(entry.file)},`
  );
  const doctestLines = doctests.map(
    (entry) =>
      `  ${JSON.stringify(entry.id)}: { file: ${JSON.stringify(entry.file)}, examples: ${entry.examples} },`
  );
  return [
    "// Generated by `bun parity/extract.ts <pokerkit checkout>`. Do not edit.",
    `export const pokerkitCommit = ${JSON.stringify(commit)};`,
    "",
    "export const unitTests = {",
    ...unitLines,
    "} as const;",
    "",
    "export const doctests = {",
    ...doctestLines,
    "} as const;",
    "",
    "export type UnitTestId = keyof typeof unitTests;",
    "export type DoctestId = keyof typeof doctests;",
    "export type SourceFile =",
    "  | (typeof unitTests)[UnitTestId]",
    '  | (typeof doctests)[DoctestId]["file"];',
    "",
  ].join("\n");
}

async function main(root: string): Promise<void> {
  const head = Bun.spawnSync(["git", "-C", root, "rev-parse", "HEAD"]);
  const commit = head.stdout.toString().trim();
  if (!commit.startsWith(pinnedCommit)) {
    throw new Error(`expected pokerkit ${pinnedCommit}, found "${commit}"`);
  }
  const files = await pythonFiles(root, "pokerkit");
  const unitTests: UnitTestEntry[] = [];
  const doctests: DoctestEntry[] = [];
  for (const file of files) {
    const source = await readFile(path.join(root, file), "utf8");
    if (file.startsWith("pokerkit/tests/")) {
      unitTests.push(...unitTestsIn(file, source));
    } else {
      doctests.push(...doctestsIn(file, source));
    }
  }
  const examples = doctests.reduce((sum, entry) => sum + entry.examples, 0);
  console.error(
    `${unitTests.length} unit tests, ${doctests.length} docstrings, ${examples} examples`
  );
  process.stdout.write(manifestSource(commit, unitTests, doctests));
}

if (import.meta.main) {
  const root = process.argv[2];
  if (root === undefined) {
    throw new Error("usage: bun parity/extract.ts <pokerkit checkout>");
  }
  await main(root);
}
